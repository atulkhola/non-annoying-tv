#!/usr/bin/env python3
"""Draws the little TV that lives in the search chip and writes MarkArt.java. Swap it for your own mark by editing the poses."""
import json, os

W, H, TOP = 44, 24, -8  # columns, rows, and the y of the first row
BODY = [(10, 1, 18, 12)]
FEET = [(13, 13, 3, 2), (22, 13, 3, 2)]
AERIAL = [(15, -3, 1, 2), (16, -1, 1, 2), (23, -3, 1, 2), (22, -1, 1, 2)]
TILTED = [(13, -3, 1, 2), (14, -2, 2, 1), (16, -1, 1, 2), (21, -3, 1, 2), (20, -2, 2, 1), (19, -1, 1, 2)]
SCREEN = [(12, 3, 14, 8)]

def pose(aerial=AERIAL, eyes=(), bar=()):
    g = [["."] * W for _ in range(H)]
    def put(x, y, w, h, c):
        for j in range(y, y + h):
            for i in range(x, x + w): g[j - TOP][i] = c
    for r in BODY + FEET + list(aerial): put(*r, "R")
    for r in SCREEN: put(*r, "K")
    for r in eyes: put(*r, "R")
    for r in bar: put(*r, "D")
    return ["".join(r) for r in g]

OPEN = [(15, 5, 2, 3), (21, 5, 2, 3)]
SHUT = [(15, 6, 2, 1), (21, 6, 2, 1)]
LEFT = [(13, 5, 2, 3), (19, 5, 2, 3)]
RIGHT = [(17, 5, 2, 3), (23, 5, 2, 3)]
scan = lambda x: [(x, 4, 2, 6)]

P = {
  "idle": pose(eyes=OPEN),
  "blink": pose(eyes=SHUT),
  "left": pose(eyes=LEFT),
  "right": pose(eyes=RIGHT),
  "perk": pose(aerial=TILTED, eyes=OPEN),
  "scanA": pose(aerial=TILTED, bar=scan(14)),
  "scanB": pose(aerial=TILTED, bar=scan(18)),
  "scanC": pose(aerial=TILTED, bar=scan(22)),
}
# Pose, then how long it holds in ms.
ROUTINE = [["idle", 1300], ["blink", 120], ["idle", 500], ["left", 320], ["right", 320], ["idle", 240], ["perk", 200]]
WRITE = [["scanA", 110], ["scanB", 110], ["scanC", 110]]
SETTLE = [["perk", 120], ["idle", 300]]
root = os.path.dirname(os.path.abspath(__file__))

# Only these columns reach the screen.
X0, X1 = 6, 40
crop = {n: [r[X0:X1] for r in g] for n, g in P.items()}
names = list(crop)
steps = lambda s: "{" + ", ".join("{%d, %d}" % (names.index(n), ms) for n, ms in s) + "}"
rows = ",\n    ".join("{" + ", ".join(json.dumps(r) for r in crop[n]) + "}" for n in names)
java = f"""package tv.home.app;

/** Generated by design/build_mark.py. Do not edit. */
final class MarkArt {{
  static final int WIDTH = {X1 - X0}, HEIGHT = {H}, IDLE = {names.index("idle")}, TILT = {names.index("perk")};
  static final int[][] ROUTINE = {steps(ROUTINE)}, WRITE = {steps(WRITE)}, SETTLE = {steps(SETTLE)};
  static final String[][] POSES = {{
    {rows}
  }};
}}
"""
open(root + "/../tv-app/app/src/main/java/tv/home/app/MarkArt.java", "w").write(java)
print("wrote MarkArt.java,", len(P), "poses")
